#!/usr/bin/env python3
"""Mastery tracker + spaced repetition for CS2680. Stdlib only.

  learn.py scaffold                 create module folders from curriculum.json
  learn.py status                   print + regenerate PROGRESS.md
  learn.py start M00                gate check, create branch module/M00-slug
  learn.py score M00 quiz 85 [-n]   log an assessment (kinds: diagnostic quiz teachback build transfer)
  learn.py master M00               enforce mastery gate, record, tag mastered/M00
  learn.py lab L3                   run the tests for one lab (labs/L3_*) and log pass/fail
  learn.py card add "Q" "A" [-m M00]   add flashcard
  learn.py card due                 list due cards
  learn.py card review ID 0-5       SM-2 grade a card
"""
import argparse, json, subprocess, sys, datetime as dt
from pathlib import Path

for _s in (sys.stdout, sys.stderr):
    try: _s.reconfigure(encoding="utf-8")
    except Exception: pass
ROOT = Path(__file__).resolve().parent.parent
CUR = json.loads((ROOT / "curriculum.json").read_text(encoding="utf-8"))
MODS = {m["id"]: m for m in CUR["modules"]}
ORDER = [m["id"] for m in CUR["modules"]]
THRESH = CUR["mastery_threshold"]
STATE = ROOT / "progress" / "state.json"
LOG = ROOT / "progress" / "log.jsonl"
CARDS = ROOT / "progress" / "cards.jsonl"
REQUIRED = {"quiz", "teachback", "build", "transfer"}  # all must be >= THRESH to master
today = lambda: dt.date.today().isoformat()


def load_state():
    s = json.loads(STATE.read_text()) if STATE.exists() else {}
    for m in ORDER:
        s.setdefault(m, {"status": "locked"})
    return s


def save_state(s):
    STATE.parent.mkdir(exist_ok=True)
    STATE.write_text(json.dumps(s, indent=2))


def log(ev):
    LOG.parent.mkdir(exist_ok=True)
    ev["date"] = dt.datetime.now().isoformat(timespec="seconds")
    with LOG.open("a", encoding="utf-8") as f:
        f.write(json.dumps(ev) + "\n")


def events():
    return [json.loads(l) for l in LOG.read_text(encoding="utf-8").splitlines()] if LOG.exists() else []


def best_scores(mid):
    """Latest score per kind (latest counts: mastery must be current, not lucky)."""
    out = {}
    for e in events():
        if e.get("type") == "score" and e["module"] == mid:
            out[e["kind"]] = e["score"]
    return out


def git(*a):
    return subprocess.run(["git", *a], cwd=ROOT, capture_output=True, text=True)


def scaffold():
    for m in CUR["modules"]:
        d = ROOT / "modules" / f"{m['id']}-{m['slug']}"
        (d / "evidence").mkdir(parents=True, exist_ok=True)
        (d / "evidence" / ".gitkeep").touch()
        readme = d / "README.md"
        if not readme.exists():
            obj = "\n".join(f"- [ ] {o}" for o in m["objectives"])
            rd = "\n".join(f"- {r}" for r in m["readings"])
            readme.write_text(
                f"# {m['id']} — {m['title']}\n\nWeeks: {m['weeks']} · Assignment: {m['assignment'] or '-'}\n\n"
                f"## Mastery objectives\n{obj}\n\n## Readings\n{rd}\n\n"
                f"## Mastery gate (all >= {THRESH}%)\n- [ ] quiz (closed-book, tutor-generated)\n- [ ] teachback (explain to tutor-as-novice)\n"
                f"- [ ] build (code/measurement in `evidence/`)\n- [ ] transfer (novel problem, not seen in lesson)\n\n"
                f"## Error log (mistakes -> root cause -> fix)\n\n## Notes\n", encoding="utf-8")
        notes = d / "notes.md"
        if not notes.exists():
            notes.write_text(f"# {m['id']} notes (my own words)\n", encoding="utf-8")
    print("scaffolded")


def render():
    s = load_state()
    done = sum(1 for m in ORDER if s[m]["status"] == "mastered")
    bar = "#" * done + "-" * (len(ORDER) - done)
    rows = ["| Module | Title | Status | Quiz | Teach | Build | Transfer | Mastered |", "|---|---|---|---|---|---|---|---|"]
    icon = {"locked": "🔒", "in_progress": "🟡", "mastered": "✅"}
    for mid in ORDER:
        sc = best_scores(mid)
        g = lambda k: str(sc.get(k, "·"))
        rows.append(f"| {mid} | {MODS[mid]['title']} | {icon[s[mid]['status']]} {s[mid]['status']} | {g('quiz')} | {g('teachback')} | {g('build')} | {g('transfer')} | {s[mid].get('mastered_on', '')} |")
    due = len(due_cards())
    txt = (f"# Progress (auto-generated by `tools/learn.py status`)\n\n`[{bar}]` {done}/{len(ORDER)} modules mastered · "
           f"{due} flashcards due · mastery threshold {THRESH}%\n\n" + "\n".join(rows) + "\n")
    (ROOT / "PROGRESS.md").write_text(txt, encoding="utf-8")
    return txt


def cmd_start(mid):
    s = load_state()
    i = ORDER.index(mid)
    reqs = MODS[mid].get("requires", [ORDER[i - 1]] if i > 0 else [])
    missing = [r for r in reqs if s[r]["status"] != "mastered"]
    if missing:
        sys.exit(f"GATE: {', '.join(missing)} not mastered. No skipping ahead.")
    s[mid]["status"] = "in_progress"
    save_state(s)
    log({"type": "start", "module": mid})
    br = f"module/{mid}-{MODS[mid]['slug']}"
    r = git("switch", "-c", br)
    if r.returncode:
        git("switch", br)
    print(f"on branch {br}")
    print(render())


def cmd_score(mid, kind, score, note):
    assert kind in REQUIRED | {"diagnostic"}, "bad kind"
    log({"type": "score", "module": mid, "kind": kind, "score": score, "note": note})
    print(f"{mid} {kind}: {score}  (need {THRESH})")


def cmd_master(mid):
    sc = best_scores(mid)
    miss = [k for k in sorted(REQUIRED) if sc.get(k, 0) < THRESH]
    if miss:
        sys.exit(f"NOT MASTERED. Below {THRESH}: " + ", ".join(f"{k}={sc.get(k,'none')}" for k in miss))
    s = load_state()
    s[mid].update(status="mastered", mastered_on=today())
    save_state(s)
    log({"type": "master", "module": mid})
    git("tag", "-f", f"mastered/{mid}")
    print(f"{mid} MASTERED. Tagged mastered/{mid}. Commit, then PR/merge branch to main.")
    print(render())


# ---- SM-2 spaced repetition ----
def cards():
    return [json.loads(l) for l in CARDS.read_text(encoding="utf-8").splitlines()] if CARDS.exists() else []


def write_cards(cs):
    CARDS.parent.mkdir(exist_ok=True)
    CARDS.write_text("".join(json.dumps(c) + "\n" for c in cs), encoding="utf-8")


def due_cards():
    return [c for c in cards() if c["due"] <= today()]


def card_add(q, a, mod):
    cs = cards()
    cs.append({"id": len(cs) + 1, "q": q, "a": a, "module": mod, "ease": 2.5, "interval": 0, "reps": 0, "due": today()})
    write_cards(cs)
    print("added", len(cs))


def card_review(cid, g):
    cs = cards()
    c = next(c for c in cs if c["id"] == cid)
    if g < 3:
        c["reps"], c["interval"] = 0, 1
    else:
        c["interval"] = 1 if c["reps"] == 0 else 6 if c["reps"] == 1 else round(c["interval"] * c["ease"])
        c["reps"] += 1
    c["ease"] = max(1.3, c["ease"] + 0.1 - (5 - g) * (0.08 + (5 - g) * 0.02))
    c["due"] = (dt.date.today() + dt.timedelta(days=c["interval"])).isoformat()
    write_cards(cs)
    log({"type": "card", "id": cid, "grade": g})
    print(f"card {cid} next in {c['interval']}d")


def cmd_lab(prefix):
    dirs = sorted((ROOT / "labs").glob(f"{prefix}_*"))
    if not dirs:
        sys.exit(f"no lab matching {prefix}_* in labs/")
    r = subprocess.run([sys.executable, "-m", "pytest", "-q", "-p", "no:cacheprovider", "."], cwd=dirs[0])
    log({"type": "lab", "lab": dirs[0].name, "passed": r.returncode == 0})
    sys.exit(r.returncode)


def main():
    p = argparse.ArgumentParser()
    sub = p.add_subparsers(dest="c", required=True)
    sub.add_parser("scaffold"); sub.add_parser("status"); sub.add_parser("lab").add_argument("lab")
    for n in ("start", "master"):
        sub.add_parser(n).add_argument("module")
    sc = sub.add_parser("score")
    sc.add_argument("module"); sc.add_argument("kind"); sc.add_argument("score", type=int); sc.add_argument("-n", "--note", default="")
    cd = sub.add_parser("card"); cs = cd.add_subparsers(dest="cc", required=True)
    a = cs.add_parser("add"); a.add_argument("q"); a.add_argument("a"); a.add_argument("-m", "--module", default="")
    cs.add_parser("due")
    r = cs.add_parser("review"); r.add_argument("id", type=int); r.add_argument("grade", type=int)
    x = p.parse_args()
    if x.c == "scaffold": scaffold()
    elif x.c == "status":
        s = load_state(); save_state(s); print(render())
    elif x.c == "start":
        cmd_start(x.module)
    elif x.c == "master": cmd_master(x.module)
    elif x.c == "lab": cmd_lab(x.lab)
    elif x.c == "score": cmd_score(x.module, x.kind, x.score, x.note)
    elif x.c == "card":
        if x.cc == "add": card_add(x.q, x.a, x.module)
        elif x.cc == "due":
            for c in due_cards(): print(c["id"], c["module"], "|", c["q"])
        else: card_review(x.id, x.grade)


if __name__ == "__main__":
    main()
